#!/bin/sh
# Prints the Homebrew formula for a release, from that release's SHA256SUMS.
#
#   scripts/homebrew-formula.sh 0.1.1 release/SHA256SUMS > Formula/betteroff.rb
#
# The release workflow runs this to update raintree-technology/homebrew-tap.
set -eu

version="$1"
sums="$2"
repo="raintree-technology/betteroff.cli"

case "$version" in
*[!0-9.]* | "") echo "version must look like 0.1.1" >&2 && exit 1 ;;
esac

sha() {
	value="$(awk -v name="betteroff-$1" '$2 == name { print $1 }' "$sums")"
	case "$value" in
	[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]*) ;;
	*) echo "no SHA-256 for betteroff-$1 in $sums" >&2 && exit 1 ;;
	esac
	[ "${#value}" -eq 64 ] || { echo "bad SHA-256 for betteroff-$1" >&2 && exit 1; }
	printf '%s' "$value"
}

darwin_arm64="$(sha darwin-arm64)"
darwin_x64="$(sha darwin-x64)"
linux_arm64="$(sha linux-arm64)"
linux_x64="$(sha linux-x64)"
base="https://github.com/$repo/releases/download/v$version"

cat <<EOF
# Generated by $repo scripts/homebrew-formula.sh for v$version. Do not edit by hand.
class Betteroff < Formula
  desc "Read your BetterOff household finances from the terminal, read-only"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/betteroff-darwin-arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/betteroff-darwin-x64"
      sha256 "$darwin_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/betteroff-linux-arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/betteroff-linux-x64"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install Dir["betteroff-*"].fetch(0) => "betteroff"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/betteroff --version").strip
  end
end
EOF
